const utf8 = "utf8";

function repositoryPath(path) {
  return resolve(repositoryRoot, path);
}

function assetPath(path) {
  return resolve(assetRoot, path);
}

async function readRepositoryText(path) {
  return readFile(repositoryPath(path), utf8);
}

async function writeAsset(path, source) {
  const target = assetPath(path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, source, utf8);
}

function replaceExactly(source, search, replacement, label) {
  const first = source.indexOf(search);
  if (first < 0 || source.indexOf(search, first + search.length) >= 0) {
    throw new Error(`Expected exactly one ${label} block in its repository source.`);
  }
  return `${source.slice(0, first)}${replacement}${source.slice(first + search.length)}`;
}

function sha256(source) {
  return createHash("sha256").update(source).digest("hex");
}

function assertThinSource(path, source) {
  for (const pattern of [
    /ReferenceRecord/u,
    /reference-record/u,
    /\/reference-records/u,
    /["'`]\/records(?:["'`/?#]|$)/u,
  ]) {
    if (pattern.test(source)) throw new Error(`Thin application template ${path} contains ${pattern}.`);
  }
}

