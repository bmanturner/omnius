import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const manifestUrl = new URL("../../../contracts/contract-manifest.json", import.meta.url);
const outputUrl = new URL("../src/internal/generated/contract-metadata.ts", import.meta.url);
const allowedArguments = new Set(["--check"]);
const unknownArguments = process.argv.slice(2).filter((argument) => !allowedArguments.has(argument));
if (unknownArguments.length > 0) {
  throw new Error(`Unknown argument(s): ${unknownArguments.join(", ")}`);
}

const manifest = JSON.parse(await readFile(manifestUrl, "utf8"));
if (
  typeof manifest !== "object" ||
  manifest === null ||
  typeof manifest.aggregate_sha256 !== "string" ||
  !/^[0-9a-f]{64}$/u.test(manifest.aggregate_sha256) ||
  typeof manifest.minimum_sdk_version !== "string" ||
  !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/u.test(manifest.minimum_sdk_version) ||
  !(
    manifest.maximum_sdk_version === null ||
    (typeof manifest.maximum_sdk_version === "string" &&
      /^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/u.test(manifest.maximum_sdk_version))
  )
) {
  throw new Error(
    `Canonical contract manifest has invalid aggregate or SDK compatibility metadata: ${fileURLToPath(manifestUrl)}`,
  );
}

const aggregate = JSON.stringify(manifest.aggregate_sha256);
const prefixedAggregate = JSON.stringify(`sha256:${manifest.aggregate_sha256}`);
const minimum = JSON.stringify(manifest.minimum_sdk_version);
const maximum = JSON.stringify(manifest.maximum_sdk_version);
const generated = `/* @generated by scripts/generate-contract-metadata.mjs from contracts/contract-manifest.json. Do not edit. */

export interface ContractCompatibilityWindow {
  readonly minimumSdkVersion: string;
  readonly maximumSdkVersion: string | null;
}

export const CONTRACT_AGGREGATE_SHA256 =
  ${aggregate} as const;
export const GENERATED_AGAINST_CONTRACT_HASH =
  ${prefixedAggregate} as const;
export const CONTRACT_COMPATIBILITY_WINDOW: ContractCompatibilityWindow = Object.freeze({
  minimumSdkVersion: ${minimum},
  maximumSdkVersion: ${maximum},
});
`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputUrl, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      `Generated contract metadata is stale. Run the package generate:contract-metadata script: ${fileURLToPath(outputUrl)}`,
    );
  }
} else {
  const current = await readFile(outputUrl, "utf8").catch(() => "");
  if (current !== generated) {
    await writeFile(outputUrl, generated, "utf8");
  }
}
